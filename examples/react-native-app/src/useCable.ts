/**
 * useCable — React hook wiring the generated typed client to a bridge.
 *
 * In an app:
 *   const add = useCable('add');
 *   const sum = await add(20, 22);
 *
 * Swaps in the mock bridge automatically when the native module is absent
 * (Storybook / unit tests), so the same hook works everywhere.
 */
import { useMemo } from 'react';
import { createReactNativeEngine, createMockBridge, createTurboModuleBridge } from '@scriptcable/react-native';

// eslint-disable-next-line @typescript-eslint/no-explicit-any
let cachedEngine: any = null;

function resolveBridge(): unknown {
  // 1. Real device: TurboModule generated by scriptcable build --hosts react-native
  try {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const NativeCable = require('./NativeCable').default;
    return createTurboModuleBridge(NativeCable);
  } catch {
    // 2. Fallback: mock (tests / Storybook). Import your own mock impl here.
    return createMockBridge({
      add: (a: number, b: number) => a + b,
      mul: (a: number, b: number) => a * b,
      greet: (name: string) => `hello, ${name}`,
    });
  }
}

export function getCableEngine() {
  if (!cachedEngine) {
    cachedEngine = createReactNativeEngine(resolveBridge());
  }
  return cachedEngine;
}

/** Typed hook — returns the export function bound to the engine. */
export function useCable(exportName: string): (...args: unknown[]) => Promise<unknown> {
  const engine = useMemo(getCableEngine, []);
  return useMemo(
    () => async (...args: unknown[]) => engine.invoke(exportName, args),
    [engine, exportName],
  );
}
