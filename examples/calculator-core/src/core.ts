/** Adds two numbers. */
export function add(a: number, b: number): number {
  return a + b;
}

/** Multiplies two numbers. */
export function mul(a: number, b: number): number {
  return a * b;
}

/** Greets someone by name. */
export function greet(name: string): string {
  return `hello, ${name}`;
}
