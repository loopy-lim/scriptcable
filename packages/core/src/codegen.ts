import type { ResolvedConfig, ScriptcableProfile } from '@scriptcable/types';
import { configToProfile } from './profile.js';

export type CodegenTarget =
  | 'node'
  | 'bun'
  | 'tauri'
  | 'react-native'
  | 'lynx'
  | 'browser';

export type CodegenResult = {
  files: Record<string, string>;
};

function header(target: string): string {
  return `/* Generated by scriptcable — do not edit by hand. Target: ${target} */\n`;
}

function paramName(e: ScriptcableProfile['exports'][number], i: number): string {
  return e.paramNames?.[i] ?? `arg${i}`;
}

function paramList(e: ScriptcableProfile['exports'][number]): string {
  return e.params.map((p, i) => `${paramName(e, i)}: ${tsType(p)}`).join(', ');
}

function argList(e: ScriptcableProfile['exports'][number]): string {
  return e.params.map((_, i) => paramName(e, i)).join(', ');
}

function docComment(e: ScriptcableProfile['exports'][number]): string {
  return e.doc ? `  /** ${e.doc.replace(/\*\//g, '*\\/')} */\n` : '';
}

function genTypes(profile: ScriptcableProfile): string {
  const lines: string[] = [
    header('types'),
    `export type ScriptcableClient = {`,
  ];
  for (const e of profile.exports) {
    if (e.doc) lines.push(`  /** ${e.doc.replace(/\*\//g, '*\\/')} */`);
    lines.push(`  ${e.export}(${paramList(e)}): ${tsType(e.returns)};`);
  }
  lines.push(`  dispose(): void;`);
  lines.push(`};\n`);
  return lines.join('\n');
}

function tsType(cls: string): string {
  switch (cls) {
    case 'f64':
    case 'f32':
    case 'u8':
    case 'u16':
    case 'u32':
    case 'i8':
    case 'i16':
    case 'i32':
      return 'number';
    case 'i64':
    case 'u64':
      return 'bigint';
    case 'bool':
      return 'boolean';
    case 'string':
    case 'cstring':
      return 'string';
    case 'bytes':
      return 'Uint8Array';
    case 'void':
      return 'void';
    default:
      return 'unknown';
  }
}

function methodBlock(profile: ScriptcableProfile): string {
  return profile.exports
    .map((e) => {
      const args = e.params.length ? `, ${argList(e)}` : '';
      return `${docComment(e)}  ${e.export}(${paramList(e)}): ${tsType(e.returns)} {
    return mod.call('${e.export}'${args}) as ${tsType(e.returns)};
  },`;
    })
    .join('\n');
}

/** Methods that call the typed N-API addon's direct functions (bytes get a Buffer copy). */
function methodBlockDirect(profile: ScriptcableProfile): string {
  return profile.exports
    .map((e) => {
      const params = paramList(e);
      const argNames = e.params.map((p, i) =>
        p === 'bytes' ? `Buffer.from(${paramName(e, i)} as Uint8Array)` : paramName(e, i),
      );
      return `${docComment(e)}  ${e.export}(${params}): ${tsType(e.returns)} {
    return addonFns['${e.export}'](${argNames.join(', ')}) as ${tsType(e.returns)};
  },`;
    })
    .join('\n');
}

function genNodeClient(
  profile: ScriptcableProfile,
  sharedRelPath: string,
  wasmRelPath: string,
  outDirRel = '.scriptcable/generated',
  outDirRoot = '.scriptcable',
): string {
  const methods = methodBlock(profile);
  const directMethods = methodBlockDirect(profile);
  return `${header('node')}
import { access, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { WASI } from 'node:wasi';
import { loadNativeLibrary, loadNativeLibrarySync } from '@scriptcable/core/native';
import { loadWasmModule } from '@scriptcable/core/wasm';
import type { ScriptcableProfile } from '@scriptcable/types';
import type { ScriptcableClient } from './types.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
// Bundlers may rewrite the module URL (e.g. .next/server chunks), so also
// search the project's generated dir and outDir root, where buildCore
// leaves the shared library / wasm.
const SEARCH_DIRS = [
  __dirname,
  join(process.cwd(), '${outDirRel}'),
  join(process.cwd(), '${outDirRoot}'),
];
const SHARED_NAME = '${sharedRelPath}';
const WASM_NAME = '${wasmRelPath}';
const ADDON_NAME = '${profile.name}.node';
const PROFILE = ${JSON.stringify(profile, null, 2)} as ScriptcableProfile;

async function exists(path: string): Promise<boolean> {
  try { await access(path); return true; } catch { return false; }
}

async function firstExisting(name: string): Promise<string | null> {
  for (const dir of SEARCH_DIRS) {
    const p = join(dir, name);
    if (await exists(p)) return p;
  }
  return null;
}

/**
 * Typed N-API direct binding — the fast path (~22-30 ns/call). Falls back
 * to the generic-FFI shared library when the addon is absent or unloadable.
 */
async function loadAddon(): Promise<Record<string, (...args: unknown[]) => unknown> | null> {
  try {
    const { createRequire } = await import('node:module');
    const req = createRequire(import.meta.url);
    for (const dir of SEARCH_DIRS) {
      try {
        return req(join(dir, ADDON_NAME)) as Record<string, (...args: unknown[]) => unknown>;
      } catch {
        /* try the next location */
      }
    }
  } catch {
    /* createRequire unavailable — fall through */
  }
  return null;
}

/** Sync variant of loadAddon — createRequire keeps the whole path synchronous. */
function loadAddonSync(): Record<string, (...args: unknown[]) => unknown> | null {
  try {
    const req = createRequire(import.meta.url);
    for (const dir of SEARCH_DIRS) {
      try {
        return req(join(dir, ADDON_NAME)) as Record<string, (...args: unknown[]) => unknown>;
      } catch {
        /* try the next location */
      }
    }
  } catch {
    /* createRequire unavailable — fall through */
  }
  return null;
}

function findSharedSync(): string | null {
  for (const dir of SEARCH_DIRS) {
    const p = join(dir, SHARED_NAME);
    if (existsSync(p)) return p;
  }
  return null;
}

export type CreateClientSyncOptions = {
  sharedPath?: string;
  /** Set false to skip the typed N-API addon and use the shared library */
  addon?: boolean;
};

/**
 * Synchronous client — no await anywhere, so it is safe in CommonJS-output
 * server bundles (where top-level await is unavailable). Prefers the typed
 * N-API addon (~24 ns/call), then the shared library via bun:ffi / koffi.
 * WASM cannot load synchronously: when no native artifact exists this
 * throws with the fix — run 'scriptcable build' first, or use the async
 * createClient() for the WASM fallback.
 */
export function createClientSync(options: CreateClientSyncOptions = {}): ScriptcableClient {
  if (options.addon !== false && !options.sharedPath) {
    const addonFns = loadAddonSync();
    if (addonFns) {
      return {
${directMethods}
  dispose() {},
      };
    }
  }
  const shared = options.sharedPath ?? findSharedSync();
  if (shared) {
    const mod = loadNativeLibrarySync(shared, PROFILE);
    return {
${methods}
  dispose() { mod.dispose(); },
    };
  }
  throw new Error(
    "No native artifacts found for '" + PROFILE.name + "' (searched: " + SEARCH_DIRS.join(', ') + '). ' +
      "Run 'scriptcable build' first, or use the async createClient() for the WASM fallback.",
  );
}

export type CreateClientOptions = {
  sharedPath?: string;
  wasmPath?: string;
  /** Opt into WASM even when a native shared library exists */
  preferWasm?: boolean;
  /** Set false to skip the typed N-API addon and use the shared library */
  addon?: boolean;
  callbacks?: Record<string, (...args: unknown[]) => unknown>;
};

export async function createClient(options: CreateClientOptions = {}): Promise<ScriptcableClient> {
  if (!options.preferWasm && options.addon !== false && !options.sharedPath) {
    const addonFns = await loadAddon();
    if (addonFns) {
      return {
${directMethods}
  dispose() {},
      };
    }
  }
  if (!options.preferWasm) {
    const shared = options.sharedPath ?? (await firstExisting(SHARED_NAME));
    if (shared) {
      const mod = await loadNativeLibrary(shared, PROFILE);
      return {
${methods}
  dispose() { mod.dispose(); },
      };
    }
  }
  const wasmPath = options.wasmPath ?? (await firstExisting(WASM_NAME)) ?? join(SEARCH_DIRS[0], WASM_NAME);
  const bytes = await readFile(wasmPath);
  // node:wasi's WASI is structurally (not nominally) the adapter the wasm
  // loader expects — the runtime shapes line up on preview1.
  const wasi = new WASI({ version: 'preview1', returnOnExit: true }) as unknown as Parameters<
    typeof loadWasmModule
  >[1]['wasi'];
  const mod = await loadWasmModule(bytes, {
    profile: PROFILE,
    wasi,
    callbacks: options.callbacks ?? {},
  });
  return {
${methods}
  dispose() { mod.dispose(); },
  };
}

export { PROFILE };
`;
}

function genBunClient(
  profile: ScriptcableProfile,
  sharedRelPath: string,
  wasmRelPath: string,
  outDirRel?: string,
  outDirRoot?: string,
): string {
  return genNodeClient(profile, sharedRelPath, wasmRelPath, outDirRel, outDirRoot).replace(
    'Target: node',
    'Target: bun',
  );
}

function genBrowserClient(profile: ScriptcableProfile, wasmRelPath: string): string {
  const methods = profile.exports
    .map((e) => {
      const params = e.params.map((_, i) => `arg${i}`).join(', ');
      const args = e.params.length ? `, ${params}` : '';
      return `  ${e.export}(${e.params.map((p, i) => `arg${i}: ${tsType(p)}`).join(', ')}): ${tsType(e.returns)} {\n    return mod.call('${e.export}'${args}) as ${tsType(e.returns)};\n  },`;
    })
    .join('\n');

  return `${header('browser')}
import { loadWasmModule, type LoadedModule } from '@scriptcable/core/wasm';
import { createMinimalWasi } from '@scriptcable/core/wasi';
import type { ScriptcableProfile } from '@scriptcable/types';
import type { ScriptcableClient } from './types.js';

const PROFILE = ${JSON.stringify(profile, null, 2)} as ScriptcableProfile;
const WASM_FILE = '${wasmRelPath}';

// Candidate locations, probed in order: next to this module (bundler dev
// servers that serve project files — vite dev), then the origin root (a
// static directory the bundler plugin copies the wasm into — Next public/,
// vite public/ → dist root). An explicit wasmUrl option always wins.
const RELATIVE_URL = new URL(WASM_FILE, import.meta.url);
function rootUrl(): URL | null {
  try {
    if (typeof document !== 'undefined') return new URL('/' + WASM_FILE, document.baseURI);
    if (typeof location !== 'undefined') return new URL('/' + WASM_FILE, location.href);
  } catch {
    /* no DOM / worker location — skip the root candidate */
  }
  return null;
}
const CANDIDATES: URL[] = [RELATIVE_URL, rootUrl()].filter((u): u is URL => u !== null);

let resolvedUrl: URL | null = null;

async function reachable(url: URL): Promise<boolean> {
  try {
    return (await fetch(url, { method: 'HEAD' })).ok;
  } catch {
    return false;
  }
}

async function resolveWasmUrl(explicit?: string | URL): Promise<URL> {
  if (explicit) return new URL(explicit);
  if (resolvedUrl) return resolvedUrl;
  for (const url of CANDIDATES) {
    if (await reachable(url)) {
      resolvedUrl = url;
      return url;
    }
  }
  // None answered HEAD (or HEAD is refused) — fall back to the original
  // candidate so its compile error surfaces exactly as before.
  return CANDIDATES[0]!;
}

/**
 * Stream-compile the module while it downloads (wasm-pack/wasm-bindgen
 * practice); falls back to fetch + arrayBuffer when the server omits the
 * application/wasm content type.
 */
async function compileModule(url: string | URL): Promise<WebAssembly.Module> {
  try {
    return await WebAssembly.compileStreaming(fetch(url));
  } catch {
    const response = await fetch(url);
    return WebAssembly.compile(await response.arrayBuffer());
  }
}

export type CreateClientOptions = {
  wasmUrl?: string | URL;
  callbacks?: Record<string, (...args: unknown[]) => unknown>;
  /** Optional WASI adapter — defaults to the built-in minimal polyfill. */
  wasi?: {
    getImportObject(): WebAssembly.Imports;
    initialize(instance: WebAssembly.Instance): void;
  };
};

export async function createClient(options: CreateClientOptions = {}): Promise<ScriptcableClient> {
  const url = await resolveWasmUrl(options.wasmUrl);
  const module = await compileModule(url);
  const mod: LoadedModule = await loadWasmModule(new Uint8Array(), {
    profile: PROFILE,
    module,
    wasi: options.wasi ?? createMinimalWasi(),
    callbacks: options.callbacks ?? {},
  });
  return {
${methods}
  dispose() { mod.dispose(); },
  };
}

export { PROFILE };
export type { ScriptcableClient } from './types.js';
`;
}

function genTauriClient(profile: ScriptcableProfile, wasmRelPath: string): string {
  // Tauri webview: same as browser, plus optional sidecar invoke bridge stub.
  return (
    genBrowserClient(profile, wasmRelPath).replace('Target: browser', 'Target: tauri') +
    `
/** Optional: call a Tauri sidecar executable that wraps the same core. */
export async function createSidecarClient(invoke: (cmd: string, args?: unknown) => Promise<unknown>) {
  return {
${profile.exports
  .map(
    (e) =>
      `    async ${e.export}(...args: unknown[]) {\n      return invoke('scriptcable_${e.export}', { args });\n    },`,
  )
  .join('\n')}
    dispose() {},
  };
}
`
  );
}

function genReactNativeClient(profile: ScriptcableProfile): string {
  return `${header('react-native')}
import type { ScriptcableClient } from './types.js';

/**
 * React Native adapter.
 *
 * Pass a bridge backed by your TurboModule:
 *   import { createTurboModuleBridge } from '@scriptcable/react-native';
 *   const bridge = createTurboModuleBridge(NativeCable);
 * For tests / Storybook use createMockBridge({ ... }).
 */
export type RnBridge = {
  call(exportName: string, args: unknown[]): unknown | Promise<unknown>;
  dispose?: () => void;
};

export function createClient(bridge: RnBridge): ScriptcableClient {
  return {
${profile.exports
  .map((e) => {
    return `${docComment(e)}    ${e.export}(${paramList(e)}) {\n      return bridge.call('${e.export}', [${argList(e)}]) as ${tsType(e.returns)};\n    },`;
  })
  .join('\n')}
    dispose() { bridge.dispose?.(); },
  };
}
`;
}

/**
 * TurboModule spec — the single native entry point is
 *   call(exportName: string, argsJson: string): Promise<string>;
 * which keeps the codegen surface tiny regardless of core size.
 */
function genTurboModuleSpec(profile: ScriptcableProfile): string {
  const rnTypes = profile.exports
    .map((e) => ` *   - ${e.export}(${e.params.join(', ')}) -> ${e.returns}`)
    .join('\n');
  return `${header('react-native turbomodule')}
import type { TurboModule } from 'react-native';
import { TurboModuleRegistry } from 'react-native';

/**
 * Native entry point for the ${profile.name} core (prefix: ${profile.abi.prefix}).
 *
 * Exports exposed through call():
${rnTypes}
 *
 * The native side dispatches on exportName and marshals argsJson.
 * Generated by scriptcable — the codegen config lives in cable.json.
 */
export interface Spec extends TurboModule {
  call(exportName: string, argsJson: string): Promise<string>;
  /** Optional: typed shortcuts when the host implements direct bindings. */
${profile.exports
  .map((e) => `  ${e.export}(${paramList(e)}): Promise<${tsType(e.returns)}>;`)
  .join('\n')}
}

export default TurboModuleRegistry.getEnforcing<Spec>('${profile.name}');
`;
}

/** RN CLI codegen config for the TurboModule above. */
function genCableCodegenConfig(profile: ScriptcableProfile): string {
  return JSON.stringify(
    {
      version: '0.2',
      codegenLanguage: 'cpp',
      specPaths: { native: ['src/NativeCable.ts'] },
      moduleProviders: { [profile.name]: 'NativeCable' },
      generated: { cpp: 'generated/', objects: ['call', ...profile.exports.map((e) => e.export)] },
    },
    null,
    2,
  ) + '\n';
}

function genLynxClient(profile: ScriptcableProfile, wasmRelPath: string): string {
  return (
    genBrowserClient(profile, wasmRelPath).replace('Target: browser', 'Target: lynx') +
    `
/**
 * Lynx: prefer a native module bridge on device (link .lib.a via NDK/JNI).
 * WASM remains an opt-in fallback for environments without native linking;
 * provide a WASI polyfill if you use it.
 */
`
  );
}

/**
 * Drop-in clients: modules whose named exports mirror the core entry's own
 * (same names, signatures, JSDoc) but route every call through the compiled
 * client. Bundler plugins redirect imports of the entry here, so app code
 * keeps importing `./core` while the bundle runs the scriptc build — the
 * "register the plugin, get the speed" contract.
 */
function dropinExportBlock(profile: ScriptcableProfile, clientExpr: string): string {
  return profile.exports
    .map((e) => {
      const args = argList(e);
      return `${docComment(e)}export function ${e.export}(${paramList(e)}): ${tsType(e.returns)} {
  return ${clientExpr}.${e.export}(${args});
}`;
    })
    .join('\n\n');
}

function genBrowserDropin(profile: ScriptcableProfile): string {
  return `${header('browser drop-in')}
import { createClient } from '../browser.js';
import type { ScriptcableClient } from '../types.js';

/**
 * Drop-in client (browser / web graphs). Initialized once at module load
 * via top-level await — every call afterwards is synchronous WASM at full
 * speed. Hosts without top-level-await support should not redirect here
 * (use the async createClient() from '@scriptcable/client' instead).
 */
const client: ScriptcableClient = await createClient();

/** The underlying client — for dispose() or advanced use. */
export function getScriptcableClient(): ScriptcableClient {
  return client;
}

${dropinExportBlock(profile, 'client')}
`;
}

function genNodeDropin(profile: ScriptcableProfile): string {
  return `${header('node drop-in')}
import { createClientSync } from '../node.js';
import type { ScriptcableClient } from '../types.js';

/**
 * Drop-in client (server graphs). No await anywhere — safe in
 * CommonJS-output server bundles. Loads the typed N-API addon, falling
 * back to the shared library; throws with the fix when no native artifact
 * has been built yet.
 */
const client: ScriptcableClient = createClientSync();

/** The underlying client — for dispose() or advanced use. */
export function getScriptcableClient(): ScriptcableClient {
  return client;
}

${dropinExportBlock(profile, 'client')}
`;
}

function genReactNativeDropin(profile: ScriptcableProfile): string {
  return `${header('react-native drop-in')}
import { createClient } from '../react-native.js';
import { createTurboModuleBridge } from '@scriptcable/react-native';
import NativeCable from '../NativeCable.js';
import type { ScriptcableClient } from '../types.js';

/**
 * Drop-in client (Metro graphs). The bridge client is created lazily on
 * first call — no top-level await needed. On device, TurboModule calls
 * resolve as Promises (same semantics as createClient(bridge) — see
 * @scriptcable/react-native); the mock bridge is synchronous.
 */
let cached: ScriptcableClient | null = null;
function client(): ScriptcableClient {
  return (cached ??= createClient(createTurboModuleBridge(NativeCable)));
}

/** The underlying client — for dispose() or advanced use. */
export function getScriptcableClient(): ScriptcableClient {
  return client();
}

${dropinExportBlock(profile, 'client()')}
`;
}

export function generateClients(
  config: ResolvedConfig,
  targets: CodegenTarget[],
  opts: { wasmFileName?: string; sharedFileName?: string; profile?: ScriptcableProfile } = {},
): CodegenResult {
  const profile = opts.profile ?? configToProfile(config);
  const wasmRel = opts.wasmFileName ?? `${config.name}.wasm`;
  const sharedRel =
    opts.sharedFileName ??
    (process.platform === 'win32'
      ? `${config.name}.dll`
      : process.platform === 'darwin'
        ? `lib${config.name}.dylib`
        : `lib${config.name}.so`);
  const files: Record<string, string> = {
    'types.ts': genTypes(profile),
  };

  for (const t of targets) {
    const outDirRoot = config.outDir ?? '.scriptcable';
    switch (t) {
      case 'node':
        files['node.ts'] = genNodeClient(profile, sharedRel, wasmRel, `${outDirRoot}/generated`, outDirRoot);
        break;
      case 'bun':
        files['bun.ts'] = genBunClient(profile, sharedRel, wasmRel, `${outDirRoot}/generated`, outDirRoot);
        break;
      case 'browser':
        files['browser.ts'] = genBrowserClient(profile, wasmRel);
        break;
      case 'tauri':
        files['tauri.ts'] = genTauriClient(profile, wasmRel);
        break;
      case 'react-native':
        files['react-native.ts'] = genReactNativeClient(profile);
        files['NativeCable.ts'] = genTurboModuleSpec(profile);
        files['cable.json'] = genCableCodegenConfig(profile);
        break;
      case 'lynx':
        files['lynx.ts'] = genLynxClient(profile, wasmRel);
        break;
    }
  }

  // Drop-in mirrors of the entry — one per generated web/server flavor.
  // Metro (React Native) needs its own: it ignores package export conditions
  // and the bridge client takes a required bridge argument.
  if (targets.includes('browser')) files['dropin/browser.ts'] = genBrowserDropin(profile);
  if (targets.includes('node')) files['dropin/node.ts'] = genNodeDropin(profile);
  if (targets.includes('react-native')) files['dropin/react-native.ts'] = genReactNativeDropin(profile);

  files['index.ts'] = `${header('index')}
export type { ScriptcableClient } from './types.js';
${targets.includes('node') ? "export { createClient as createNodeClient, PROFILE } from './node.js';\n" : ''}${targets.includes('bun') ? "export { createClient as createBunClient } from './bun.js';\n" : ''}${targets.includes('browser') ? "export { createClient as createBrowserClient } from './browser.js';\n" : ''}${targets.includes('tauri') ? "export { createClient as createTauriClient, createSidecarClient } from './tauri.js';\n" : ''}${targets.includes('react-native') ? "export { createClient as createReactNativeClient } from './react-native.js';\n" : ''}${targets.includes('lynx') ? "export { createClient as createLynxClient } from './lynx.js';\n" : ''}`;

  return { files };
}
