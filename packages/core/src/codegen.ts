import type { ScriptcaConfig, ScriptcaProfile } from '@scriptca/types';
import { configToProfile } from './profile.js';

export type CodegenTarget =
  | 'node'
  | 'bun'
  | 'tauri'
  | 'react-native'
  | 'lynx'
  | 'browser';

export type CodegenResult = {
  files: Record<string, string>;
};

function header(target: string): string {
  return `/* Generated by scriptca — do not edit by hand. Target: ${target} */\n`;
}

function genTypes(profile: ScriptcaProfile): string {
  const lines: string[] = [
    header('types'),
    `export type ScriptcaClient = {`,
  ];
  for (const e of profile.exports) {
    const params = e.params
      .map((p, i) => `arg${i}: ${tsType(p)}`)
      .join(', ');
    lines.push(`  ${e.export}(${params}): ${tsType(e.returns)};`);
  }
  lines.push(`  dispose(): void;`);
  lines.push(`};\n`);
  return lines.join('\n');
}

function tsType(cls: string): string {
  switch (cls) {
    case 'f64':
    case 'f32':
    case 'u8':
    case 'u16':
    case 'u32':
    case 'i8':
    case 'i16':
    case 'i32':
      return 'number';
    case 'i64':
    case 'u64':
      return 'bigint';
    case 'bool':
      return 'boolean';
    case 'string':
    case 'cstring':
      return 'string';
    case 'bytes':
      return 'Uint8Array';
    case 'void':
      return 'void';
    default:
      return 'unknown';
  }
}

function genNodeClient(profile: ScriptcaProfile, wasmRelPath: string): string {
  const methods = profile.exports
    .map((e) => {
      const params = e.params.map((_, i) => `arg${i}`).join(', ');
      const args = e.params.length ? `, ${params}` : '';
      return `  ${e.export}(${e.params.map((p, i) => `arg${i}: ${tsType(p)}`).join(', ')}): ${tsType(e.returns)} {\n    return mod.call('${e.export}'${args}) as ${tsType(e.returns)};\n  },`;
    })
    .join('\n');

  return `${header('node')}
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { WASI } from 'node:wasi';
import { loadWasmModule, type LoadedModule } from '@scriptca/core/wasm';
import type { ScriptcaProfile } from '@scriptca/types';
import type { ScriptcaClient } from './types.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_WASM = join(__dirname, '${wasmRelPath}');
const PROFILE = ${JSON.stringify(profile, null, 2)} as ScriptcaProfile;

export type CreateClientOptions = {
  wasmPath?: string;
  callbacks?: Record<string, (...args: unknown[]) => unknown>;
};

export async function createClient(options: CreateClientOptions = {}): Promise<ScriptcaClient> {
  const bytes = await readFile(options.wasmPath ?? DEFAULT_WASM);
  const wasi = new WASI({ version: 'preview1', returnOnExit: true });
  const mod: LoadedModule = await loadWasmModule(bytes, {
    profile: PROFILE,
    wasi,
    callbacks: options.callbacks ?? {},
  });
  return {
${methods}
  dispose() { mod.dispose(); },
  };
}

export { PROFILE };
`;
}

function genBunClient(profile: ScriptcaProfile, wasmRelPath: string): string {
  // Bun can use Node WASI compatibility or its own; we reuse the same loader.
  return genNodeClient(profile, wasmRelPath).replace("Target: node", "Target: bun");
}

function genBrowserClient(profile: ScriptcaProfile, wasmRelPath: string): string {
  const methods = profile.exports
    .map((e) => {
      const params = e.params.map((_, i) => `arg${i}`).join(', ');
      const args = e.params.length ? `, ${params}` : '';
      return `  ${e.export}(${e.params.map((p, i) => `arg${i}: ${tsType(p)}`).join(', ')}): ${tsType(e.returns)} {\n    return mod.call('${e.export}'${args}) as ${tsType(e.returns)};\n  },`;
    })
    .join('\n');

  return `${header('browser')}
import { loadWasmModule, type LoadedModule } from '@scriptca/core/wasm';
import type { ScriptcaProfile } from '@scriptca/types';
import type { ScriptcaClient } from './types.js';

const PROFILE = ${JSON.stringify(profile, null, 2)} as ScriptcaProfile;
const DEFAULT_URL = new URL('${wasmRelPath}', import.meta.url);

export type CreateClientOptions = {
  wasmUrl?: string | URL;
  callbacks?: Record<string, (...args: unknown[]) => unknown>;
  /** Browser WASI adapter with getImportObject() + initialize(instance) */
  wasi: {
    getImportObject(): WebAssembly.Imports;
    initialize(instance: WebAssembly.Instance): void;
  };
};

export async function createClient(options: CreateClientOptions): Promise<ScriptcaClient> {
  const url = options.wasmUrl ?? DEFAULT_URL;
  const response = await fetch(url);
  const bytes = await response.arrayBuffer();
  const mod: LoadedModule = await loadWasmModule(bytes, {
    profile: PROFILE,
    wasi: options.wasi,
    callbacks: options.callbacks ?? {},
  });
  return {
${methods}
  dispose() { mod.dispose(); },
  };
}

export { PROFILE };
`;
}

function genTauriClient(profile: ScriptcaProfile, wasmRelPath: string): string {
  // Tauri webview: same as browser, plus optional sidecar invoke bridge stub.
  return (
    genBrowserClient(profile, wasmRelPath).replace('Target: browser', 'Target: tauri') +
    `
/** Optional: call a Tauri sidecar executable that wraps the same core. */
export async function createSidecarClient(invoke: (cmd: string, args?: unknown) => Promise<unknown>) {
  return {
${profile.exports
  .map(
    (e) =>
      `    async ${e.export}(...args: unknown[]) {\n      return invoke('scriptca_${e.export}', { args });\n    },`,
  )
  .join('\n')}
    dispose() {},
  };
}
`
  );
}

function genReactNativeClient(profile: ScriptcaProfile): string {
  return `${header('react-native')}
import type { ScriptcaClient } from './types.js';

/**
 * React Native adapter.
 *
 * Verified path in this release: a host-provided native module / JSI bridge
 * that exposes the same export names. WASM-on-RN requires a runtime such as
 * react-native-quick-wasm (not bundled); until then pass a bridge object.
 */
export type RnBridge = {
  call(exportName: string, args: unknown[]): unknown | Promise<unknown>;
  dispose?: () => void;
};

export function createClient(bridge: RnBridge): ScriptcaClient {
  return {
${profile.exports
  .map((e) => {
    const params = e.params.map((p, i) => `arg${i}: ${tsType(p)}`).join(', ');
    const args = e.params.map((_, i) => `arg${i}`).join(', ');
    return `    ${e.export}(${params}) {\n      return bridge.call('${e.export}', [${args}]) as ${tsType(e.returns)};\n    },`;
  })
  .join('\n')}
    dispose() { bridge.dispose?.(); },
  };
}
`;
}

function genLynxClient(profile: ScriptcaProfile, wasmRelPath: string): string {
  return (
    genBrowserClient(profile, wasmRelPath).replace('Target: browser', 'Target: lynx') +
    `
/**
 * Lynx (https://lynxjs.org) runs a JS runtime with Rspeedy/Rsbuild.
 * Load the WASM the same way as a browser host; provide a WASI polyfill
 * (e.g. @wasmer/wasi or a minimal stub for programs that don't touch FS).
 */
`
  );
}

export function generateClients(
  config: ScriptcaConfig,
  targets: CodegenTarget[],
  opts: { wasmFileName?: string } = {},
): CodegenResult {
  const profile = configToProfile(config);
  const wasmRel = opts.wasmFileName ?? `${config.name}.wasm`;
  const files: Record<string, string> = {
    'types.ts': genTypes(profile),
  };

  for (const t of targets) {
    switch (t) {
      case 'node':
        files['node.ts'] = genNodeClient(profile, wasmRel);
        break;
      case 'bun':
        files['bun.ts'] = genBunClient(profile, wasmRel);
        break;
      case 'browser':
        files['browser.ts'] = genBrowserClient(profile, wasmRel);
        break;
      case 'tauri':
        files['tauri.ts'] = genTauriClient(profile, wasmRel);
        break;
      case 'react-native':
        files['react-native.ts'] = genReactNativeClient(profile);
        break;
      case 'lynx':
        files['lynx.ts'] = genLynxClient(profile, wasmRel);
        break;
    }
  }

  files['index.ts'] = `${header('index')}
export type { ScriptcaClient } from './types.js';
${targets.includes('node') ? "export { createClient as createNodeClient, PROFILE } from './node.js';\n" : ''}${targets.includes('bun') ? "export { createClient as createBunClient } from './bun.js';\n" : ''}${targets.includes('browser') ? "export { createClient as createBrowserClient } from './browser.js';\n" : ''}${targets.includes('tauri') ? "export { createClient as createTauriClient, createSidecarClient } from './tauri.js';\n" : ''}${targets.includes('react-native') ? "export { createClient as createReactNativeClient } from './react-native.js';\n" : ''}${targets.includes('lynx') ? "export { createClient as createLynxClient } from './lynx.js';\n" : ''}`;

  return { files };
}
