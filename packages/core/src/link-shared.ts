/**
 * Link a scriptc library archive (.lib.a) into a loadable shared library
 * (.so / .dylib / .dll) for Bun (bun:ffi) and Node (optional koffi).
 */
import { spawn } from 'node:child_process';
import { mkdir, writeFile, access, constants, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { ScriptcableToolchainError } from '@scriptcable/types';
import { which } from './which.js';

async function run(
  cmd: string,
  args: string[],
): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (d: Buffer) => (stdout += d.toString()));
    child.stderr.on('data', (d: Buffer) => (stderr += d.toString()));
    child.on('error', reject);
    child.on('close', (code) => resolvePromise({ code: code ?? 1, stdout, stderr }));
  });
}

/** Minimal stubs for unused async/promise symbols pulled in by archive objects. */
export const STUB_SOURCE = `/* auto-generated by scriptcable — unused archive refs */
void scr_promise_settled_void(void) {}
void scr_promise_settled_ref(void) {}
void scr_promise_settled_now(void) {}
int scr_promise_payload_truthy(void) { return 0; }
`;

/**
 * Android (ARM-translation) only: the scriptc runtime references libc's
 * stdio DATA objects, whose eager relocations cannot resolve through the
 * translation loader at dlopen. Null definitions bind those references
 * locally — safe for cores that never print; a core that writes to stdio
 * would fault and should route logging through the platform instead.
 */
export const ANDROID_DATA_SHIMS = `/* auto-generated by scriptcable — translation-loader data shims */
void *stderr = (void *)0;
void *stdout = (void *)0;
void *environ = (void *)0;
`;

/**
 * NDK C++ driver for an android target (e.g. 'aarch64-linux-android') —
 * searches ANDROID_NDK_HOME / ANDROID_NDK_ROOT / <ANDROID_HOME>/ndk/*.
 */
async function findNdkClangxx(target: string): Promise<string | undefined> {
  const wrapper = `${target}24-clang++`;
  const roots = [process.env.ANDROID_NDK_HOME, process.env.ANDROID_NDK_ROOT].filter(
    (v): v is string => Boolean(v),
  );
  const home = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT;
  if (home) {
    const ndkDir = join(home, 'ndk');
    try {
      const versions = (await readdir(ndkDir)).sort();
      if (versions.length) roots.push(join(ndkDir, versions[versions.length - 1]!));
    } catch {
      /* no ndk dir */
    }
  }
  for (const root of roots) {
    for (const host of ['linux-x86_64', 'x86_64', 'darwin-x86_64']) {
      const candidate = join(root, 'toolchains', 'llvm', 'prebuilt', host, 'bin', wrapper);
      if (existsSync(candidate)) return candidate;
    }
  }
  return undefined;
}

export type LinkSharedOptions = {
  /** Path to scriptc .lib.a */
  archivePath: string;
  /** Output shared library path */
  outPath: string;
  cwd?: string;
  /** Cross-compile target triple (e.g. 'aarch64-linux-android') — forces
   * `zig cc -target`, the only multi-target driver we rely on. Android
   * (bionic) keeps pthread/dl in libc, so those libs are skipped. */
  target?: string;
  /** Extra translation units compiled with the same driver and linked in
   * (android: the generated JNI dispatch glue). */
  extraSources?: string[];
  /** Include directories for extraSources compilation. */
  includeDirs?: string[];
};

export function sharedLibraryExt(platform = process.platform): string {
  if (platform === 'darwin') return '.dylib';
  if (platform === 'win32') return '.dll';
  return '.so';
}

/** File name dlopen/bun:ffi expect: lib{name}.so / lib{name}.dylib / {name}.dll */
export function sharedLibraryFileName(name: string, platform = process.platform): string {
  const ext = sharedLibraryExt(platform);
  if (platform === 'win32') return `${name}${ext}`;
  return `lib${name}${ext}`;
}

export async function linkSharedLibrary(options: LinkSharedOptions): Promise<string> {
  const archivePath = resolve(options.archivePath);
  const outPath = resolve(options.outPath);
  await access(archivePath, constants.R_OK);

  // Windows: link with `zig cc` when available — clang there drives
  // lld-link (MSVC), which cannot read the GNU-ar archive scriptc emits
  // (LNK1143). zig cc is the GNU-family driver scriptc itself uses on
  // Windows; clang stays the fallback. Android prefers the NDK driver —
  // its DSOs carry real DT_NEEDED libc.so entries, which ARM-translation
  // devices resolve natively (the zig-linked one fails eager stdio-data
  // relocations at dlopen); zig cc stays the no-NDK fallback.
  const cross = options.target !== undefined;
  const isAndroid = cross && options.target!.includes('-android');
  const ndkClang = isAndroid ? await findNdkClangxx(options.target!) : undefined;
  const zig = !ndkClang && (cross || process.platform === 'win32') ? await which('zig') : undefined;
  const clang = cross ? undefined : ((await which('clang')) ?? (await which('cc')));
  if (!zig && !ndkClang && !clang) {
    throw new ScriptcableToolchainError(
      cross
        ? `zig cc or the Android NDK is required to cross-link ${options.target}.`
        : 'clang (or cc) is required to link the native shared library.',
      cross
        ? 'Install the Android NDK (ANDROID_NDK_HOME or ANDROID_HOME/ndk) — the NDK driver links real bionic DT_NEEDED entries, which ARM-translation devices resolve — or zig 0.13.x (ziglang.org).'
        : 'Install a C toolchain:\n' +
            '  Linux:  sudo apt install clang\n' +
            '  macOS:  xcode-select --install\n' +
            '  Windows: zig (ziglang.org) — zig cc drives the linker\n' +
            'Or build with --target wasm for the WASI fallback.',
    );
  }
  const linker = ndkClang ?? zig ?? clang!;
  const linkerArgs = ndkClang
    ? []
    : zig
      ? ['cc', ...(cross ? ['-target', options.target!] : [])]
      : [];

  await mkdir(dirname(outPath), { recursive: true });
  const stubC = join(dirname(outPath), 'scriptcable-stubs.c');
  const stubO = join(dirname(outPath), 'scriptcable-stubs.o');
  await writeFile(stubC, isAndroid && !ndkClang ? STUB_SOURCE + ANDROID_DATA_SHIMS : STUB_SOURCE);

  const compileStub = await run(linker, [...linkerArgs, '-c', stubC, '-o', stubO]);
  if (compileStub.code !== 0) {
    throw new ScriptcableToolchainError(
      `Failed to compile link stubs:\n${compileStub.stderr}`,
    );
  }

  const extraObjs: string[] = [];
  let extraIdx = 0;
  for (const src of options.extraSources ?? []) {
    const srcPath = resolve(src);
    const obj = join(dirname(outPath), `link-extra-${extraIdx++}.o`);
    const std = /\.cpp$|\.cc$|\.cxx$/.test(srcPath) ? ['-std=c++17'] : [];
    const inc = (options.includeDirs ?? []).flatMap((d) => ['-I', d]);
    const c = await run(linker, [...linkerArgs, ...std, ...inc, '-c', srcPath, '-o', obj]);
    if (c.code !== 0) {
      throw new ScriptcableToolchainError(`Failed to compile ${srcPath}:\n${c.stderr}`);
    }
    extraObjs.push(obj);
  }

  const args: string[] = ['-shared', '-o', outPath];
  if (isAndroid) {
    // The archive objects use direct PC-relative references, which a shared
    // library may only keep if the referenced symbols bind locally — a
    // version script exports just the JNI entry points and localizes the
    // rest (also the right visibility for a dlopen'd module anyway).
    const mapPath = join(dirname(outPath), 'cable-version.map');
    await writeFile(mapPath, '{\n  global:\n    Java_*;\n  local:\n    *;\n};\n');
    // lld binds the value to --version-script directly — as a separate arg it
    // would swallow the next flag.
    args.push(`-Wl,--version-script=${mapPath}`);
    if (!ndkClang) {
      // zig has no bionic to resolve (error: libc not available) and a
      // dlopen'd module doesn't want one — libc symbols stay undefined here
      // and the Android runtime binds them.
      args.push('-nostdlib');
    }
    // NO --whole-archive on android: pulling every runtime object drags in
    // fs/console code whose eager DATA relocations (stderr, environ) fail to
    // resolve on ARM-translation devices at dlopen. Selective pulling keeps
    // only the objects the core actually references.
  }
  if (isAndroid) {
    // Selective object pulling — see the whole-archive note above.
    args.push(archivePath, '-Wl,--allow-shlib-undefined');
  } else if (process.platform === 'darwin') {
    args.push('-Wl,-force_load,' + archivePath);
  } else if (process.platform === 'win32') {
    // zig cc speaks GNU ld: whole-archive keeps every object of the archive
    args.push('-Wl,--whole-archive', archivePath, '-Wl,--no-whole-archive');
    args.push('-Wl,--allow-shlib-undefined');
  } else {
    args.push('-Wl,--whole-archive', archivePath, '-Wl,--no-whole-archive');
    // Unused FS/async objects may reference symbols we stubbed or never call.
    args.push('-Wl,--allow-shlib-undefined');
  }
  args.push(stubO, ...extraObjs);
  if (isAndroid) {
    // Bionic folds math/pthread/dl into libc — zig's android sysroot ships
    // no separate libm/pthread stubs, so link with nothing extra.
  } else {
    if (process.platform !== 'win32') args.push('-lm', '-lpthread');
    if (process.platform === 'linux') args.push('-ldl');
  }

  const link = await run(linker, [...linkerArgs, ...args]);
  if (link.code !== 0) {
    throw new ScriptcableToolchainError(
      `Failed to link shared library from ${archivePath}:\n${link.stderr || link.stdout}`,
      'Ensure clang can link for this host. Try: scriptcable doctor',
    );
  }
  return outPath;
}

/** Merge scriptc .lib.a + stubs into lib{name}.a usable with -lstatic={name}. */
export async function buildCompleteStaticArchive(options: {
  archivePath: string;
  outPath: string;
}): Promise<string> {
  const archivePath = resolve(options.archivePath);
  const outPath = resolve(options.outPath);
  await access(archivePath, constants.R_OK);
  const clang = (await which('clang')) ?? (await which('cc'));
  if (!clang) {
    throw new ScriptcableToolchainError(
      'clang is required to prepare the static archive for native hosts.',
      'Install clang, or use the shared library (.so) from Bun/Node.',
    );
  }
  await mkdir(dirname(outPath), { recursive: true });
  const work = join(dirname(outPath), '.scriptcable-static-work');
  await mkdir(work, { recursive: true });
  const stubC = join(work, 'stubs.c');
  const stubO = join(work, 'stubs.o');
  await writeFile(stubC, STUB_SOURCE);
  const c1 = await run(clang, ['-c', stubC, '-o', stubO]);
  if (c1.code !== 0) throw new ScriptcableToolchainError(c1.stderr);
  // Extract archive objects into work dir then re-pack with stubs
  const extract = await run('bash', ['-c', `cd "${work}" && ar x "${archivePath}"`]);
  if (extract.code !== 0) throw new ScriptcableToolchainError(extract.stderr || extract.stdout);
  const pack = await run('bash', [
    '-c',
    `cd "${work}" && rm -f "${outPath}" && ar rcs "${outPath}" *.o`,
  ]);
  if (pack.code !== 0) throw new ScriptcableToolchainError(pack.stderr || pack.stdout);
  return outPath;
}
